// The hooks module as Claude Code loads it: register.ts and everything it
// imports, in one file with no imports of its own (the module loader runs
// none).
//
//   bun hooks/bundle.ts           write register.bundle.js (`just build-hooks`)
//   bun hooks/bundle.ts --check   fail unless that file is what this builds
//                                 (`just check-hooks-bundle`, in `just ci` and CI)
//
// The plugin is installed as the repository's tree, with no build step, so
// the bundle is a tracked file beside its source.
//
// The bundle depends on the source and on the bundler's version, and on
// nothing else: it is built from the repository's root and keeps no file
// names. Its first line records the bun that built it. CI checks the bundle
// with that bun, so the check says whether the bundle is stale, and a bun
// release does not fail it. A check under another bun that builds the same
// text passes; one that builds other text cannot tell a stale bundle from a
// bundler that writes differently, and asks for a rebuild, which records the
// bun of the rebuild.
//
// Design rationale: not minified. `claude plugin validate` reads the module's
// `$` calls off this file and names the functions they are made from, so
// those names and `$.noun.method(...)` spellings have to survive.
import * as path from "node:path";

const HOOKS_DIR = import.meta.dir;
const REPO_ROOT = path.dirname(HOOKS_DIR);
export const MODULE_SOURCE = path.join(HOOKS_DIR, "register.ts");
export const MODULE_BUNDLE = path.join(HOOKS_DIR, "register.bundle.js");

/** The first line, naming the bun that built the bundle. CI reads the
 * version off it (.github/workflows/ci.yml). */
function header(bunVersion: string): string {
  return `// Generated by \`just build-hooks\` with bun ${bunVersion} from register.ts; edit that file, not this one.\n`;
}
const HEADER_LINE = /^\/\/ Generated by `just build-hooks` with bun (\S+) .*\n/;

/** The comment line Bun puts before each module it inlines, naming the
 * module's file. The name depends on where the build runs and on how
 * node_modules is laid out (`node_modules/.bun/valibot@<version>+<hash>/…`
 * under the isolated linker), not on the source, so the lines are left out.
 * Bun drops every other comment of the source, so a line of this shape is
 * only ever such a name. */
const MODULE_NAME_LINE = /^\/\/ \S+\.[cm]?[jt]s\n/gm;

/** The bundle of the hooks module without its header: the same text for the
 * same source and bundler, whatever the directory it is built from and
 * however node_modules is laid out. */
export async function bundleBody(): Promise<string> {
  const built = await Bun.build({
    entrypoints: [MODULE_SOURCE],
    root: REPO_ROOT,
    target: "browser",
    format: "esm",
    minify: false,
  });
  if (!built.success) {
    throw new AggregateError(built.logs, "bundling the hooks module failed");
  }
  const [output, ...rest] = built.outputs;
  if (output === undefined || rest.length > 0) {
    throw new Error(`bundling the hooks module made ${built.outputs.length} files, not 1`);
  }
  return (await output.text()).replace(MODULE_NAME_LINE, "");
}

/** A bundle file split into the bun it records and the rest, or undefined
 * when it has no header. */
export function readBundle(text: string): { bunVersion: string; body: string } | undefined {
  const match = HEADER_LINE.exec(text);
  const bunVersion = match?.[1];
  if (match === null || bunVersion === undefined) return undefined;
  return { bunVersion, body: text.slice(match[0].length) };
}

/** Why the bundle in the tree is not the one this bun builds now, or
 * undefined when it is. */
export async function staleness(): Promise<string | undefined> {
  const name = path.basename(MODULE_BUNDLE);
  const tracked = readBundle(await Bun.file(MODULE_BUNDLE).text());
  if (tracked === undefined) return `${name} has no header naming the bun that built it`;
  if (tracked.body === (await bundleBody())) return undefined;
  return tracked.bunVersion === Bun.version
    ? `${name} is not the bundle of the source as it is now`
    : `${name} was built by bun ${tracked.bunVersion}, and bun ${Bun.version} builds other text from the source: either the bundle is stale or the bundlers write differently`;
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const why = await staleness();
    if (why !== undefined) {
      process.stderr.write(`${why}; run \`just build-hooks\`\n`);
      process.exit(1);
    }
  } else {
    await Bun.write(MODULE_BUNDLE, header(Bun.version) + (await bundleBody()));
  }
}
