// The hooks module as Claude Code loads it: composer-fill.ts and everything it
// imports, in one file with no imports of its own (the module loader runs
// none).
//
//   bun hooks/bundle.ts           write composer-fill.bundle.js (`just build-hooks`)
//   bun hooks/bundle.ts --check   fail unless that file is what this builds
//                                 (`just check-hooks-bundle`, part of `just ci`)
//
// The plugin is installed as the repository's tree, with no build step, so
// the bundle is a tracked file beside its source.
//
// Design rationale: the check is a recipe of `just ci` (which `just push`
// runs) rather than a test. The bundle's bytes depend on the bundler's
// version, and GitHub CI runs the latest bun, so a byte comparison there
// would fail on every bun release until the bundle is rebuilt by that bun.
//
// Design rationale: not minified. `claude plugin validate` reads the module's
// `$` calls off this file and names the functions they are made from, so
// those names and `$.noun.method(...)` spellings have to survive.
import * as path from "node:path";

const HOOKS_DIR = import.meta.dir;
export const MODULE_SOURCE = path.join(HOOKS_DIR, "composer-fill.ts");
export const MODULE_BUNDLE = path.join(HOOKS_DIR, "composer-fill.bundle.js");

const HEADER =
  "// Generated by `just build-hooks` from composer-fill.ts; edit that file, not this one.\n";

/** The bundle of the hooks module, as text. */
export async function bundleModule(): Promise<string> {
  const built = await Bun.build({
    entrypoints: [MODULE_SOURCE],
    target: "browser",
    format: "esm",
    minify: false,
  });
  if (!built.success) {
    throw new AggregateError(built.logs, "bundling the hooks module failed");
  }
  const [output, ...rest] = built.outputs;
  if (output === undefined || rest.length > 0) {
    throw new Error(`bundling the hooks module made ${built.outputs.length} files, not 1`);
  }
  return HEADER + (await output.text());
}

if (import.meta.main) {
  const bundle = await bundleModule();
  if (process.argv.includes("--check")) {
    if ((await Bun.file(MODULE_BUNDLE).text()) !== bundle) {
      process.stderr.write(
        `${path.basename(MODULE_BUNDLE)} is not the bundle of the source as it is now; run \`just build-hooks\`\n`,
      );
      process.exit(1);
    }
  } else {
    await Bun.write(MODULE_BUNDLE, bundle);
  }
}
